import 'dart:convert';
import 'dart:io';

import 'package:shelf/shelf.dart';
import 'package:shelf/shelf_io.dart' as shelf_io;
import 'package:shelf_router/shelf_router.dart';

import '../lib/services/brief_parser.dart';
import '../lib/services/devpost_service.dart';
import '../lib/services/gitlab_service.dart';
import '../lib/services/github_service.dart';

void main() async {
  final port = int.parse(Platform.environment['PORT'] ?? '8080');
  final ip = InternetAddress.anyIPv4;

  final briefParser = BriefParserService();
  final devpostService = DevpostService();
  final gitLabService = GitLabService();
  final gitHubService = GitHubService();

  final router = Router()
    ..get('/health', _healthCheckHandler)
    ..post('/tasks/parse-brief', (Request req) => _parseBriefHandler(req, briefParser, devpostService))
    ..post('/tasks/provision-repo', (Request req) => _provisionRepoHandler(req, gitLabService, gitHubService))
    ..post('/tasks/commit-files', (Request req) => _commitFilesHandler(req, gitLabService, gitHubService))
    ..post('/webhooks/pubsub', _pubsubWebhookHandler);

  final handler = Pipeline()
      .addMiddleware(logRequests())
      .addMiddleware(_jsonResponseMiddleware)
      .addHandler(router.call);

  final server = await shelf_io.serve(handler, ip, port);
  print('🚀 Dart Functional Node running on http://${server.address.host}:${server.port}');
}

Response _healthCheckHandler(Request request) {
  return Response.ok(
    jsonEncode({
      'status': 'healthy',
      'service': 'dart-functional-node',
      'version': '1.0.0',
      'timestamp': DateTime.now().toUtc().toIso8601String(),
    }),
  );
}

Future<Response> _parseBriefHandler(
  Request request,
  BriefParserService parser,
  DevpostService devpost,
) async {
  try {
    final payloadString = await request.readAsString();
    Map<String, dynamic> body = {};
    if (payloadString.isNotEmpty) {
      body = jsonDecode(payloadString);
    }

    final rawHackathons = body['hackathons'];
    if (rawHackathons == null || (rawHackathons is List && rawHackathons.isEmpty)) {
      // Direct live discovery via DevpostService function
      final result = await devpost.fetchAndFilterHackathons(
        minPrizePool: body['min_prize_pool'] ?? 1000,
        requireOnline: body['require_online'] ?? true,
      );
      return Response.ok(jsonEncode(result));
    }

    final result = parser.parseAndFilterOpportunities(body);
    return Response.ok(jsonEncode(result));
  } catch (e, st) {
    print('Error in parseBrief: $e\n$st');
    return Response.internalServerError(
      body: jsonEncode({'status': 'error', 'message': e.toString()}),
    );
  }
}

Future<Response> _provisionRepoHandler(
  Request request,
  GitLabService gitLab,
  GitHubService gitHub,
) async {
  try {
    final payloadString = await request.readAsString();
    if (payloadString.isEmpty) {
      return Response.badRequest(body: jsonEncode({'error': 'Empty request body'}));
    }
    final Map<String, dynamic> body = jsonDecode(payloadString);
    final String repoName = body['repo_name'] ?? '';
    final String provider = (body['provider'] ?? 'github').toString().toLowerCase();
    final String description = body['description'] ?? 'Autonomous prototype repository';
    final String readmeContent = body['readme_content'] ?? '# $repoName\n\nGenerated by Agent-First Enterprise.';

    if (repoName.isEmpty) {
      return Response.badRequest(
        body: jsonEncode({'error': 'Missing required parameter: repo_name'}),
      );
    }

    final Map<String, dynamic> result;
    if (provider == 'gitlab') {
      result = await gitLab.provisionRepository(
        repoName: repoName,
        description: description,
        readmeContent: readmeContent,
      );
    } else {
      result = await gitHub.provisionRepository(
        repoName: repoName,
        description: description,
        readmeContent: readmeContent,
      );
    }

    return Response.ok(jsonEncode(result));
  } catch (e, st) {
    print('Error in provisionRepo: $e\n$st');
    return Response.internalServerError(
      body: jsonEncode({'status': 'error', 'message': e.toString()}),
    );
  }
}

Future<Response> _commitFilesHandler(
  Request request,
  GitLabService gitLab,
  GitHubService gitHub,
) async {
  try {
    final payloadString = await request.readAsString();
    if (payloadString.isEmpty) {
      return Response.badRequest(body: jsonEncode({'error': 'Empty request body'}));
    }
    final Map<String, dynamic> body = jsonDecode(payloadString);
    final String provider = (body['provider'] ?? 'github').toString().toLowerCase();
    final String repoName = body['repo_name'] ?? '';
    final String owner = body['owner'] ?? 'Merdzhanov';
    final List<dynamic> rawFiles = body['files'] ?? [];
    final List<Map<String, dynamic>> files = rawFiles.cast<Map<String, dynamic>>();

    final Map<String, dynamic> result;
    if (provider == 'gitlab') {
      final dynamic projectId = body['project_id'] ?? repoName;
      result = await gitLab.commitFiles(
        projectId: projectId,
        repoName: repoName,
        files: files,
      );
    } else {
      result = await gitHub.commitFiles(
        owner: owner,
        repoName: repoName,
        files: files,
      );
    }

    return Response.ok(jsonEncode(result));
  } catch (e, st) {
    print('Error in commitFiles: $e\n$st');
    return Response.internalServerError(
      body: jsonEncode({'status': 'error', 'message': e.toString()}),
    );
  }
}

Future<Response> _pubsubWebhookHandler(Request request) async {
  try {
    final payloadString = await request.readAsString();
    if (payloadString.isEmpty) {
      return Response.badRequest(body: jsonEncode({'error': 'Empty payload'}));
    }

    final Map<String, dynamic> body = jsonDecode(payloadString);
    final Map<String, dynamic>? message = body['message'];
    if (message == null) {
      return Response.badRequest(body: jsonEncode({'error': 'Invalid Pub/Sub envelope format'}));
    }

    final String? base64Data = message['data'];
    Map<String, dynamic> taskPayload = {};
    if (base64Data != null) {
      final String decodedString = utf8.decode(base64Decode(base64Data));
      taskPayload = jsonDecode(decodedString);
      print('📥 Received Pub/Sub async task: ${taskPayload['task_id']} (${taskPayload['event_type']})');
    }

    return Response.ok(
      jsonEncode({
        'status': 'acknowledged',
        'task_id': taskPayload['task_id'] ?? 'unknown',
        'timestamp': DateTime.now().toUtc().toIso8601String(),
      }),
    );
  } catch (e, st) {
    print('Pub/Sub Webhook Error: $e\n$st');
    return Response.internalServerError(
      body: jsonEncode({'error': 'Task processing failed', 'details': e.toString()}),
    );
  }
}

Middleware _jsonResponseMiddleware = (Handler innerHandler) {
  return (Request request) async {
    final response = await innerHandler(request);
    return response.change(
      headers: {'content-type': 'application/json', ...response.headers},
    );
  };
};
